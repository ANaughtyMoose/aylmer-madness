let lang = 'fr';

// The English version. Thomas, 2026-09-07: « in the Quebec education system
// you can do your exams in English, but they're horrible photocopies that are
// almost impossible to read. Make it easy enough to switch to English, but
// then everything is hard to read. » So: one click on the menu gets you the
// English copy; what you get is the departmental Xerox — a rushed, literal
// translation (the strings below), on paper that has been through the machine
// four times (the `.photocopy` rules in style.css). The French is the master
// copy and always will be. Anything the English table does not have falls
// through to it, exactly like the exam did.
export function setLang(next) {
  lang = next === 'en' ? 'en' : 'fr';
  return lang;
}
export function getLang() { return lang; }
export function languages() {
  return [['fr', 'Français québécois (l’originale)'], ['en', 'English (photocopie)']];
}

export function t(key) {
  if (lang === 'en' && Object.prototype.hasOwnProperty.call(EN, key)) return EN[key];
  if (Object.prototype.hasOwnProperty.call(FR, key)) return FR[key];
  return key;
}

