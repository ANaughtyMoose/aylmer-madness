// The English version. Thomas, 2026-09-07, wanted the departmental photocopy:
// easy to switch to, hard to read. Tom, 20 Oct 2026: real English controls for
// the English setting, so an anglophone friend can play. The EN table above
// is plain English now; the French is still the master copy and anything the
// English table does not have falls through to it.
export function setLang(next) {
  lang = next === 'en' ? 'en' : 'fr';
  return lang;
}
export function getLang() { return lang; }
export function languages() {
  return [['fr', 'Français québécois (l’originale)'], ['en', 'English']];
}

export function t(key) {
  if (lang === 'en' && Object.prototype.hasOwnProperty.call(EN, key)) return EN[key];
  if (Object.prototype.hasOwnProperty.call(FR, key)) return FR[key];
  return key;
}

